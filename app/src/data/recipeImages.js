export function getRecipeImage(recipe) {
  // Online recipes may reuse a name with different ingredients.
  if (recipe?.source === 'online') return null
  const name = typeof recipe === 'string' ? recipe : recipe?.name ?? recipe?.recipe_name
  return RECIPE_IMAGES.get(String(name || '').trim().toLowerCase()) ?? null
}

export function getRecipeImageMap(recipes = []) {
  return new Map(recipes.map((recipe) => [recipe.id, getRecipeImage(recipe)]))
}
